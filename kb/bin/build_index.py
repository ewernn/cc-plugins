#!/usr/bin/env python3
"""Regenerate INDEX.md — the depth-1 view an agent loads to navigate the whole corpus.

One line per entry: id, date, title, tags, and the Setup sentence. Small enough that a
thousand entries still fit in a context window, which is what makes loose semantic search
work without embeddings.

    python3 bin/build_index.py [--kb PATH]
"""
import argparse
import glob
import os
import re
import sys

FRONT = re.compile(r"^---\n(.*?)\n---\n(.*)$", re.S)
SETUP = re.compile(r"^Setup:\s*(.+?)(?=\n[A-Z][a-z]+:|\n\n|\Z)", re.M | re.S)


def field(front, name):
    m = re.search(rf"^{name}:\s*(.+?)$", front, re.M)
    if not m:
        return ""
    return m.group(1).strip().strip('"')


def read_entry(path):
    m = FRONT.match(open(path).read())
    if not m:
        raise ValueError(f"{path}: no YAML frontmatter")
    front, body = m.group(1), m.group(2)
    title = field(front, "title")
    if not title:
        raise ValueError(f"{path}: no title in frontmatter")
    setup = SETUP.search(body)
    return {
        "id": field(front, "id") or os.path.basename(path)[:-3],
        "date": field(front, "published") or "unknown",
        "title": title,
        "tags": field(front, "tags").strip("[]"),
        "setup": " ".join(setup.group(1).split()) if setup else "",
        "enriched": bool(field(front, "enriched")),
    }


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--kb", default=os.environ.get("KB_PATH"),
                    help="corpus root (default: $KB_PATH)")
    args = ap.parse_args()
    if not args.kb:
        sys.exit("FATAL: pass --kb or set KB_PATH; refusing to guess the corpus location")
    if not os.path.isdir(os.path.join(args.kb, "entries")):
        sys.exit(f"FATAL: {args.kb} has no entries/ directory")

    entries, stubs = [], 0
    for path in sorted(glob.glob(os.path.join(args.kb, "entries", "*.md"))):
        e = read_entry(path)
        stubs += not e["enriched"]
        entries.append(e)
    if not entries:
        sys.exit("FATAL: no entries found")

    entries.sort(key=lambda e: (e["date"] or ""), reverse=True)

    out = [
        "# Index",
        "",
        "Depth 1 of the corpus, one line per entry. Generated by `bin/build_index.py` — "
        "do not edit by hand.",
        "",
        f"{len(entries)} entries, {stubs} awaiting enrichment.",
        "",
    ]
    for e in entries:
        mark = "" if e["enriched"] else "  *[stub]*"
        out.append(f"- **{e['title']}**{mark}  \n"
                   f"  `{e['id']}` · {e['date']} · {e['tags']}"
                   + (f"  \n  {e['setup']}" if e["setup"] else ""))

    dest = os.path.join(args.kb, "INDEX.md")
    open(dest, "w").write("\n".join(out) + "\n")
    print(f"{dest}: {len(entries)} entries ({stubs} stubs), "
          f"{len('\n'.join(out)) // 4} tokens approx")


if __name__ == "__main__":
    main()
